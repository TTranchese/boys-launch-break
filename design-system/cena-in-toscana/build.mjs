/** Generate shared CSS without introducing a Sass runtime dependency. */
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const source = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(source, "../..");
const output = path.join(root, "public/design-system");
const check = process.argv.includes("--check");
const tokens = readFileSync(path.join(source, "tokens.scss"), "utf8");
const variables = Object.fromEntries(
    [...tokens.matchAll(/(--[\w-]+)\s*:\s*([^;]+);/g)]
        .map((match) => [match[1], match[2]]),
);
const dark = tokens.match(/\[data-theme="dark"\]\s*\{([^}]+)\}/)?.[1];
if (!dark) throw new Error("Missing dark theme tokens");

const header = "/* Generated by design-system/cena-in-toscana/build.mjs. */\n";
function emit(file, contents) {
    const generated = header + contents;
    if (check) {
        if (readFileSync(file, "utf8") !== generated) {
            throw new Error(`Stale generated styles: ${file}`);
        }
    } else {
        writeFileSync(file, generated);
    }
}

mkdirSync(output, { recursive: true });
emit(path.join(output, "tokens.css"), tokens +
    `\n@media (prefers-color-scheme: dark) {\n:root:not([data-theme="light"]) {${dark}}\n}\n`);
emit(path.join(output, "preview.css"), readFileSync(path.join(source, "preview.scss"), "utf8"));
// CSS custom properties do not resolve in media queries. Resolve only the
// breakpoint expression at generation time; all other tokens stay live.
const appStyles = readFileSync(path.join(source, "app.scss"), "utf8")
    .replace(/@media\s*\(width < var\((--[\w-]+)\)\)/g, (_, token) => {
        if (!variables[token]) throw new Error(`Unknown breakpoint: ${token}`);
        return `@media (width < ${variables[token]})`;
    });
const appSource = readFileSync(path.join(source, "app.scss"), "utf8");
if (/#[\da-f]{3,8}\b|\brgba?\(|\d+(?:px|rem|ms)\b/i.test(appSource)) {
    throw new Error("App styles must use design tokens for colors, sizes and timing.");
}
for (const match of appSource.matchAll(/var\((--[\w-]+)/g)) {
    // --person-color is a per-participant alias supplied by the marker.
    if (!(match[1] in variables) && match[1] !== "--person-color") {
        throw new Error(`Unknown app design token: ${match[1]}`);
    }
}
emit(path.join(root, "app/globals.css"), appStyles);
console.log(check ? "Generated styles are current." : "Generated shared tokens, app styles, and preview styles.");
